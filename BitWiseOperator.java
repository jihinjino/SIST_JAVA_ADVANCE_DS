package com.Basics;

public class BitWiseOperator {

	public static void main(String[] args) {
		
		/*
		 * BITWISE AND &
		 * BITWISE OR |
		 * BITWISE NOT ~
		 * RIGHT SHIFT >>
		 * LEFT SHIFT << 
		 */
		System.out.println(5&7);
		System.out.println(9 | 7);
		System.out.println(~-5);
		System.out.println(8 >> 3);
		System.out.println(7 << 2);
	}

}
